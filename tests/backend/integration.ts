    assert.ok((await adminReports(stranger)).items.some(x=>x.id===complaint.id));
    await moderate(stranger,{action:'ban',userId:seller,reason:'Synthetic ban test'});
    await assert.rejects(()=>getListing(listing.id,buyer),{code:'not_found'});
    await moderate(stranger,{action:'unban',userId:seller,reportId:complaint.id,reason:'Synthetic unban test'});
    assert.equal((await getListing(listing.id,buyer)).sellerId,seller);
    check('reports, explicit admin authorization, ban and unban');
    const otherConversation=await openConversation(stranger,listing.id);
    await assert.rejects(()=>createOffer(buyer,conversation.id,{priceCents:49000},randomUUID()),{code:'price_changed'});
    await assert.rejects(()=>createOffer(seller,conversation.id,{priceCents:50000},randomUUID()),{code:'forbidden'});
    const offerA=await createOffer(buyer,conversation.id,{priceCents:50000},randomUUID()),offerB=await createOffer(stranger,otherConversation.id,{priceCents:50000},randomUUID());
    const outcomes=await Promise.allSettled([resolveOffer(seller,offerA.id,{status:'accepted'}),resolveOffer(seller,offerB.id,{status:'accepted'})]);
    assert.equal(outcomes.filter(x=>x.status==='fulfilled').length,1);
    assert.equal((await db.query("SELECT count(*)::int AS count FROM offers WHERE listing_id=$1 AND status='accepted'",[listing.id])).rows[0].count,1);check('concurrent acceptance sells a device only once');
