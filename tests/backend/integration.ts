    const key=randomUUID();
    const [listing,repeated]=await Promise.all([createListing(seller,input,key),createListing(seller,input,key)]);
    assert.equal(listing.id,repeated.id);assert.match(listing.number,/^\d{10,}$/);check('concurrent publication is idempotent');
    await assert.rejects(()=>createListing(seller,{...input,priceCents:60000},key),{code:'idempotency_conflict'});
    await assert.rejects(()=>createListing(seller,{...input,specs:{...input.specs,simLock:'unknown'}},randomUUID()),{code:'invalid_input'});check('invalid variants and reused keys rejected');
    const publicListing=await getListing(listing.id,buyer);assert.equal(publicListing.privateSpecs,null);assert.ok(!JSON.stringify(publicListing).includes('PRIVATE-TEST-SERIAL'));
    await assert.rejects(()=>updateListing(listing.id,buyer,{version:1,priceCents:1}),{code:'not_found'});check('private fields and listing ownership protected');
    const cheaper=await createListing(seller,{...input,priceCents:40000},randomUUID());
    const firstPage=await listListings(buyer,new URLSearchParams({sort:'price-asc',limit:'1',minPriceCents:'40000'}));
    assert.equal(firstPage.items[0].id,cheaper.id);assert.ok(firstPage.nextCursor);
    const nextPage=await listListings(buyer,new URLSearchParams({sort:'price-asc',limit:'1',minPriceCents:'40000',cursor:firstPage.nextCursor!}));
    assert.equal(nextPage.items[0].id,listing.id);
    const nearby=await listListings(buyer,new URLSearchParams({lat:'49.14',lng:'9.22',radiusKm:'20',sort:'nearest'}));
    assert.ok(nearby.items.some(x=>x.id===listing.id));
    assert.equal((await listListings(buyer,new URLSearchParams({shipping:'yes'}))).items.some(x=>x.id===listing.id),false);
    check('server search filters, stable pagination, price sorting and local radius');
    const conversation=await openConversation(buyer,listing.id);
    await assert.rejects(()=>listMessages(stranger,conversation.id,null),{code:'not_found'});
    await updateProfile(buyer,{name:'Renamed Buyer'});
