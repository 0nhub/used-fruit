    assert.equal((await db.query('SELECT name,email,deleted_at FROM users WHERE id=$1',[seller])).rows[0].email,null);
    assert.equal((await db.query('SELECT status FROM listings WHERE id=$1',[listing.id])).rows[0].status,'deleted');check('account deletion removes public content and private account data');
