    check('transient delivery retries stop after five attempts; uncertain handoffs are not resent');
    if(process.env.USED_FRUIT_VERIFY_RESTORE==='1')execFileSync('python3',['scripts/ops/verify-restore.py'],{stdio:'inherit'});
