    assert.notEqual(session.refreshToken,rotated.refreshToken);
    await assert.rejects(()=>refreshSession(session.refreshToken),{code:'unauthorized'});
    await assert.rejects(()=>refreshSession(rotated.refreshToken),{code:'unauthorized'});check('refresh token reuse revokes the entire family');
    // Exercise the real claim/transaction path without contacting any delivery provider.
    const deliveries:string[]=[];
    const transport={sendEmail:async(to:string)=>{deliveries.push(to);return 'test-provider-id';},sendPush:async()=>"test-push-id"};
