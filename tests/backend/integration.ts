    const jobs=(await db.query('SELECT *,extract(epoch from (due_at-created_at))::int AS delay FROM notification_outbox WHERE message_id=$1',[message.id])).rows;
    assert.equal(jobs.length,2);assert.equal(jobs.find(x=>x.channel==='email').delay,120);check('one durable email job per message, due after 120 seconds');
    const email=jobs.find(x=>x.channel==='email');
    assert.equal(await transaction(async c=>shouldDeliver(await eligibility(c,email.id))),true);
    await updateConversation(seller,conversation.id,{readSequence:message.sequence});
    assert.equal(await transaction(async c=>shouldDeliver(await eligibility(c,email.id))),false);check('read message suppresses email');
    const second=await sendMessage(buyer,conversation.id,{text:'Second test'},randomUUID());
    const secondJob=(await db.query("SELECT id FROM notification_outbox WHERE message_id=$1 AND channel='email'",[second.id])).rows[0];
    assert.notEqual(secondJob.id,email.id);
    await updateConversation(seller,conversation.id,{readSequence:second.sequence});
