    const native=await transaction(c=>createSession(c,buyer,'ios'));
    assert.equal((await authenticate(new NextRequest('https://staging.usedfruit.de/api/v1/me',{headers:{Authorization:'Bearer '+native.accessToken}})))?.id,buyer);
    const web=await transaction(c=>createSession(c,buyer,'web'));
    const cookie=SESSION_COOKIE+'='+seal({kind:'session',sid:web.id,sub:buyer,name:'Ignored display name',exp:Math.floor(Date.now()/1000)+300});
    await assert.rejects(()=>authenticate(new NextRequest('https://staging.usedfruit.de/api/v1/me',{method:'PATCH',headers:{cookie,origin:'https://attacker.invalid'}})),{code:'invalid_origin'});
    assert.equal((await authenticate(new NextRequest('https://staging.usedfruit.de/api/v1/me',{headers:{cookie}})))?.id,buyer);
    await db.query("UPDATE sessions SET expires_at=now()-interval '1 second' WHERE id=$1",[native.id]);
    await assert.rejects(()=>authenticate(new NextRequest('https://staging.usedfruit.de/api/v1/listings',{headers:{Authorization:'Bearer '+native.accessToken}}),false),{code:'unauthorized'});
    check('Web and native sessions resolve the same ID; CSRF and expired bearer tokens rejected');
    const original=await sharp({create:{width:8,height:8,channels:3,background:'#00ff00'}}).jpeg().withMetadata().toBuffer();
    const uploaded=await uploadMedia(seller,new Request('https://staging.usedfruit.de/api/v1/media',{method:'POST',headers:{'content-type':'image/jpeg'},body:new Uint8Array(original)}));mediaIds.push(uploaded.id);
