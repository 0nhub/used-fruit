    assert.equal(await transaction(async c=>shouldDeliver(await eligibility(c,secondJob.id))),false);
    await updateProfile(seller,{emailNotifications:true});
    await updateConversation(seller,conversation.id,{muted:true});
    assert.equal(await transaction(async c=>shouldDeliver(await eligibility(c,secondJob.id))),false);
    await updateConversation(seller,conversation.id,{muted:false,active:true});
    const push=(await db.query("SELECT id FROM notification_outbox WHERE message_id=$1 AND channel='push'",[second.id])).rows[0];
    assert.equal(await transaction(async c=>shouldDeliver(await eligibility(c,push.id))),false);check('independent deadlines, email preference, mute and active-chat push suppression');
    await setBlock(seller,buyer,true);
    await assert.rejects(()=>getListing(listing.id,buyer),{code:'not_found'});
    await assert.rejects(()=>publicProfile(buyer,seller),{code:'not_found'});
    await assert.rejects(()=>sendMessage(buyer,conversation.id,{text:'blocked'},randomUUID()),{code:'not_found'});
    assert.equal((await listListings(buyer,new URLSearchParams())).items.some(x=>x.id===listing.id),false);
    assert.equal((await db.query('SELECT state FROM notification_outbox WHERE id=$1',[secondJob.id])).rows[0].state,'cancelled');
    await setBlock(seller,buyer,false);check('reciprocal block applies to search, detail, profile, messaging and pending delivery');
